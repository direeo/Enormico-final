function parseSafeInteger(value) {
  const parsed = Number(value);
  if (!Number.isSafeInteger(parsed)) throw new RangeError('Database integer exceeds the safe JavaScript integer range.');
  return parsed;
}

types.setTypeParser(20, parseSafeInteger);
types.setTypeParser(1700, parseSafeInteger);

function numberedParameters(sql) {
  let index = 0;
  return sql.replace(/\?/g, () => `$${++index}`);
}

function normalizeIntegerResults(result) {
  const integerFields = new Set(result.fields
    .filter(field => field.dataTypeID === 20 || field.dataTypeID === 1700)
    .map(field => field.name));
  for (const row of result.rows) {
    for (const field of integerFields) {
      if (typeof row[field] === 'string') row[field] = parseSafeInteger(row[field]);
    }
  }
  return result;
}

function createDatabaseAdapter({ query, withTransaction, close }) {
  const transactionContext = new AsyncLocalStorage();

  async function execute(sql, params = []) {
    const client = transactionContext.getStore();
    const result = await (client
      ? client.query(numberedParameters(sql), params)
      : query(numberedParameters(sql), params));
    return normalizeIntegerResults(result);
  }

  function prepare(sql) {
    return {
      get: async (...params) => (await execute(sql, params)).rows[0],
      all: async (...params) => (await execute(sql, params)).rows,
      run: async (...params) => {
        const result = await execute(sql, params);
        return {
          lastInsertRowid: result.rows[0]?.id || 0,
          changes: result.rowCount ?? result.rows.length
        };
      }
    };
  }

  return {
    prepare,
    query: execute,
    exec: sql => execute(sql),
    transaction: work => withTransaction(client => transactionContext.run(client, work)),
    close
  };
}

function createDatabase(connectionString = process.env.DATABASE_URL) {
  if (!connectionString) throw new Error('DATABASE_URL must be configured for the PostgreSQL database.');
  const pool = new Pool({ connectionString, max: 5 });
  pool.on('error', error => {
    console.error(`Idle PostgreSQL connection error (code=${error.code || 'UNKNOWN'}).`);
  });

  async function withTransaction(work) {
    const client = await pool.connect();
    let releaseError;
    try {
      await client.query('BEGIN');
      const result = await work(client);
      await client.query('COMMIT');
      return result;
    } catch (error) {
      try {
        await client.query('ROLLBACK');
      } catch (rollbackError) {
        releaseError = rollbackError;
        console.error(`PostgreSQL rollback failed (code=${rollbackError.code || 'UNKNOWN'}).`);
      }
      throw error;
    } finally {
      client.release(releaseError);
    }
  }

  return createDatabaseAdapter({
    query: (sql, params) => pool.query(sql, params),
    withTransaction,
    close: () => pool.end()
  });
}

