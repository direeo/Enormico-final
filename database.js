async function initializeDatabase(db) {
  await db.exec(`CREATE TABLE IF NOT EXISTS schema_migrations (
    version INTEGER PRIMARY KEY,
    applied_at BIGINT NOT NULL
  )`);

  await db.transaction(async () => {
    await db.exec('SELECT pg_advisory_xact_lock(8274001)');
    const migration = await db.prepare('SELECT version FROM schema_migrations WHERE version = ?').get(1);
    if (migration) return;

    for (const statement of SCHEMA_STATEMENTS) await db.exec(statement);
    const insertPlan = db.prepare(`INSERT INTO investment_plans
      (rate, minimum, maximum, duration_days, pool_target)
      VALUES (?, ?, ?, ?, ?) ON CONFLICT (rate) DO NOTHING`);
    for (const plan of PLAN_SEEDS) {
      await insertPlan.run(plan.rate, plan.minimum, plan.maximum, plan.durationDays, plan.maximum);
    }
    await db.prepare('INSERT INTO schema_migrations (version, applied_at) VALUES (?, ?)')
      .run(1, Date.now());
  });
}

